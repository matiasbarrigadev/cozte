import assert from "node:assert/strict";
import { existsSync } from "node:fs";
import { chromium } from "playwright";

const systemChrome = process.platform === "win32" ? "C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe" : null;
const executablePath = process.env.CHROME_PATH ?? (systemChrome && existsSync(systemChrome) ? systemChrome : undefined);
const baseUrl = (process.env.BASE_URL ?? "http://localhost:3000").replace(/\/$/, "");
const browser = await chromium.launch({
  headless: true,
  ...(executablePath ? { executablePath } : {}),
});
try {
  const landing = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const landingResponse = await landing.goto(baseUrl, { waitUntil: "networkidle" });
  assert.equal(landingResponse?.status(), 200, "public landing should be available without signing in");
  await landing.getByRole("heading", { name: /Lo que produces tiene un costo/i }).waitFor();
  assert.equal(await landing.getByText("Para quienes hacen cosas reales").count(), 0, "hero tag should be removed");
  await landing.getByRole("link", { name: "Cozte, inicio" }).waitFor();
  assert.equal(await landing.locator(".cozte-logo-mark").count() > 0, true, "brand mark should appear in the landing header");
  assert.equal(await landing.locator('link[rel="icon"][href="/cozte-mark.svg"]').count(), 1, "brand mark should be the SVG favicon");
  await landing.getByText("Ejemplo: papel interior de $9.000 a $10.000").waitFor();
  await landing.getByText("+$100", { exact: true }).waitFor();
  assert.equal(await landing.getByRole("link", { name: /Explorar la demo/i }).count(), 1);
  assert.equal(await landing.getByRole("link", { name: /Crear cuenta/i }).count() > 0, true);
  const featureCard = landing.getByRole("article").first();
  const featureIcon = featureCard.locator(".cozte-animated-icon");
  const featureIconBeforeHover = await featureIcon.innerHTML();
  const featureBox = await featureCard.boundingBox();
  assert.ok(featureBox, "feature card should be visible");
  await featureCard.hover({ position: { x: featureBox.width - 12, y: featureBox.height - 12 } });
  await landing.waitForTimeout(160);
  assert.notEqual(await featureIcon.innerHTML(), featureIconBeforeHover, "hovering a reactive card should animate its icon");
  await landing.screenshot({ path: "../../tmp/cozte-landing.png", fullPage: true });
  const landingMobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  await landingMobile.goto(baseUrl, { waitUntil: "networkidle" });
  await landingMobile.getByRole("heading", { name: /Lo que produces tiene un costo/i }).waitFor();
  assert.equal(await landingMobile.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, "landing must not overflow horizontally on mobile");
  await landingMobile.screenshot({ path: "../../tmp/cozte-landing-mobile.png", fullPage: true });
  await landingMobile.close();
  await landing.close();
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  await page.goto(`${baseUrl}/demo`, { waitUntil: "networkidle" });
  await page.getByRole("heading", { name: "Costos de tus productos" }).waitFor();
  assert.equal(await page.locator(".cozte-animated-icon").count() >= 8, true, "dashboard should use animated action icons");
  const dashboardButton = page.getByRole("button", { name: "Dashboard" });
  const dashboardIcon = dashboardButton.locator(".cozte-animated-icon");
  const iconBeforeHover = await dashboardIcon.innerHTML();
  const buttonBox = await dashboardButton.boundingBox();
  assert.ok(buttonBox, "dashboard button should be visible");
  await dashboardButton.hover({ position: { x: buttonBox.width - 8, y: buttonBox.height / 2 } });
  await page.waitForTimeout(160);
  assert.notEqual(await dashboardIcon.innerHTML(), iconBeforeHover, "hovering the button outside the icon should animate it");
  const sidebarStyle = await page.locator('[data-sidebar="sidebar"]').first().evaluate((element) => {
    const style = getComputedStyle(element);
    return { foreground: style.getPropertyValue("--sidebar-foreground").trim(), backgroundImage: style.backgroundImage, backdropFilter: style.backdropFilter };
  });
  assert.match(sidebarStyle.foreground, /^lab\(9\d/, "sidebar text should use the light brand color");
  assert.match(sidebarStyle.backgroundImage, /gradient/, "sidebar should have a translucent dark surface");
  assert.match(sidebarStyle.backdropFilter, /blur/, "sidebar should use backdrop blur");
  assert.equal(await page.getByRole("row").count(), 4);
  await page.screenshot({ path: "../../tmp/cozte-dashboard.png", fullPage: true });
  await page.getByRole("button", { name: "Costos de producción" }).click();
  await page.getByRole("heading", { name: "Costos de producción" }).waitFor();
  await page.getByRole("button", { name: "Tablero" }).click();
  await page.getByRole("heading", { name: "Papel", exact: true }).waitFor();
  await page.getByRole("button", { name: "Lista" }).click();
  await page.getByRole("button", { name: "Tabla" }).click();
  await page.getByRole("button", { name: "Papel", exact: true }).click();
  assert.equal(await page.getByRole("row").count(), 2, "category filter should keep only the matching material");
  await page.getByRole("button", { name: "Todas", exact: true }).click();
  await page.getByRole("spinbutton", { name: "Precio de Papel interior" }).fill("10000");
  await page.getByRole("spinbutton", { name: "Precio de Papel interior" }).press("Tab");
  await page.getByText("Puede cambiar el costeo de 3 productos").waitFor();
  await page.screenshot({ path: "../../tmp/cozte-sheet.png", fullPage: true });
  await page.getByRole("button", { name: "Revisar impacto" }).click();
  await page.getByRole("heading", { name: "Antes de confirmar" }).waitFor();
  assert.equal(await page.getByText("$3.110").count() > 0, true);
  await page.screenshot({ path: "../../tmp/cozte-review.png", fullPage: true });
  await page.getByRole("button", { name: "Dashboard" }).click();
  await page.getByRole("button", { name: "Abrir Cuaderno A5 · tapa dura" }).click();
  await page.getByRole("heading", { name: "Cuaderno A5 · tapa dura" }).waitFor();
  await page.screenshot({ path: "../../tmp/cozte-product.png", fullPage: true });
  await page.getByRole("button", { name: "Comprobantes" }).click();
  await page.getByRole("heading", { name: "Comprobantes" }).waitFor();
  await page.getByRole("button", { name: "Cozte AI" }).click();
  await page.getByRole("heading", { name: "Cozte AI", exact: true }).waitFor();
  await page.getByText("¿Qué productos terminados y empacados fabrican, dónde y cómo?").waitFor();
  assert.equal(await page.getByRole("heading", { name: "Mapa de producción" }).count(), 0);
  assert.equal(await page.getByRole("heading", { name: "Reglas descubiertas" }).count(), 0);
  await page.screenshot({ path: "../../tmp/cozte-chat.png", fullPage: true });
  await page.getByRole("button", { name: "Historial" }).click();
  await page.getByRole("heading", { name: "Historial de costos" }).waitFor();
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  await mobile.goto(`${baseUrl}/demo`, { waitUntil: "networkidle" });
  await mobile.getByRole("heading", { name: "Costos de tus productos" }).waitFor();
  await mobile.screenshot({ path: "../../tmp/cozte-mobile.png", fullPage: true });
  await mobile.getByRole("button", { name: "Toggle Sidebar" }).click();
  await mobile.getByRole("button", { name: "Costos de producción" }).click();
  await mobile.getByRole("heading", { name: "Costos de producción" }).waitFor();
  await mobile.waitForTimeout(400);
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, "mobile page should not overflow horizontally");
  await mobile.screenshot({ path: "../../tmp/cozte-sheet-mobile.png", fullPage: true });
  await mobile.getByRole("button", { name: "Toggle Sidebar" }).click();
  await mobile.getByRole("button", { name: "Cozte AI" }).click();
  await mobile.getByRole("heading", { name: "Cozte AI", exact: true }).waitFor();
  await mobile.keyboard.press("Escape");
  await mobile.waitForTimeout(400);
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, "mobile chat should not overflow horizontally");
  await mobile.screenshot({ path: "../../tmp/cozte-chat-mobile.png", fullPage: true });
  const cron = await mobile.request.get(`${baseUrl}/api/cron/freshness`);
  assert.equal(cron.status(), 401, "cron must reject requests without a secret");
  await mobile.close();
  console.log("Demo smoke test passed");
} finally {
  await browser.close();
}
